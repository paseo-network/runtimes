//! People leaf-call classifier for value transfers.
//!
//! Nested dispatch (Utility/Proxy/Multisig/as_derivative/XCM Transact) is gated by the
//! runtime's `BaseCallFilter` via `BlockValueTransfersWhenFlagSet`, so this matcher does NOT
//! recurse.

use crate::{Runtime, RuntimeCall};
use frame_support::traits::Contains;

pub struct PeopleValueTransferFilter;

impl Contains<RuntimeCall> for PeopleValueTransferFilter {
	fn contains(call: &RuntimeCall) -> bool {
		match call {
			RuntimeCall::Assets(inner) => assets_call_targets_protected_asset(inner),

			RuntimeCall::Coinage(inner) => coinage_call_requires_value_transfer_auth(inner),

			RuntimeCall::AssetConversion(inner) =>
				asset_conversion_call_moves_protected_asset(inner),

			_ => false,
		}
	}
}

fn coinage_call_requires_value_transfer_auth(call: &indiv_pallet_coinage::Call<Runtime>) -> bool {
	use indiv_pallet_coinage::Call;
	// Exhaustive on purpose: a newly-added coinage call won't compile here until it's
	// explicitly classified as requiring value-transfer auth or not.
	match call {
		// Calls that spend or release coin-denominated value on behalf of the holder.
		Call::split { .. } |
		Call::transfer { .. } |
		Call::load_recycler_with_coin { .. } |
		Call::unload_recycler_into_coin { .. } |
		Call::unload_recycler_into_external_asset { .. } |
		Call::pay_for_recycler_unload_fee_token_with_coin { .. } |
		Call::pay_for_recycler_unload_fee_token_with_native { .. } |
		Call::pay_for_recycler_unload_fee_token_with_external_asset { .. } |
		// v0.3.1, call index 9. REPLACES `unload_recycler_into_external_asset_and_vouchers`,
		// which held the SAME index and was also gated here. Same class: it unloads a holder's
		// coin value out to the external asset.
		Call::unload_recycler_into_external_asset_and_loaded_coins { .. } |
		// v0.3.1, call index 17. Unloads value out of an archived recycler to the external
		// asset; signed by the holder, spends coin-denominated value.
		Call::unload_archived_recycler_into_external_asset { .. } |
		// v0.3.1, call index 19. Signed (`SponsorOrigin`), and its optional `initial_funding`
		// moves an arbitrary `(currency, amount)` out of the creator's balance -- which may be
		// the protected asset. Gated.
		Call::create_sponsored_instance { .. } |
		// v0.3.1, call index 20. Moves an arbitrary currency from the signer into a pot.
		Call::fund_pot { .. } |
		// v0.3.1, call index 21. Pays an arbitrary currency out of a pot to the signer.
		Call::withdraw_pot_funds { .. } |
		Call::unload_recycler_into_external_asset_non_anonymous { .. } |
		Call::unload_recyclers_into_external_asset_non_anonymous { .. } |
		Call::unload_recycler_into_coins { .. } |
		Call::direct_offboard_coin_into_external_asset { .. } => true,

		// Loading a recycler from an external asset moves value *into* the coinage system
		// from the caller's external-asset balance; it never spends an existing coin, so
		// the value-transfer gate does not apply.
		Call::load_recycler_with_external_asset { .. } |
		Call::load_recycler_with_external_asset_unpaid { .. } |
		Call::load_recycler_with_external_asset_unpaid_batch { .. } |
		// Admin-only (`AdminOrigin`, wired to `EnsureRoot`) instance configuration. No holder
		// value moves and the caller cannot direct funds to itself.
		Call::create_sufficient_instance { .. } |
		Call::make_instance_sufficient { .. } |
		Call::make_instance_sponsored { .. } |
		// Permissionless, but it only re-prices an instance's own load collateral: value moves
		// between the pot's free balance and its holds, never out to a caller-chosen account.
		// The signer is not a beneficiary, so the value-transfer gate does not apply.
		Call::collapse_load_deposits { .. } |
		// Permissionless/authorized housekeeping that only reclaims expired or dust state. These
		// touch no holder's coin value (and several are authorized, not signed by a holder).
		Call::clean_recycler { .. } |
		Call::clean_consumed_free_token { .. } |
		Call::clean_paid_unload_token_ring { .. } |
		Call::clean_recycler_dust { .. } |
		Call::clean_paid_unload_token_dust { .. } |
		Call::delete_expired_paid_unload_token_collection { .. } => false,

		// Uninhabited placeholder variant generated by FRAME; never constructed.
		Call::__Ignore(..) => false,
	}
}

/// The AMM moves the protected asset without going through `pallet_assets`' own calls, so
/// without this arm `AssetConversion` would be a route around the protected-asset gate: a swap
/// or a liquidity operation naming the protected asset would move it under a plain signed
/// origin.
///
/// Exhaustive on purpose, like the coinage matcher: a newly-added `pallet-asset-conversion`
/// call will not compile here until it is explicitly classified.
fn asset_conversion_call_moves_protected_asset(
	call: &pallet_asset_conversion::Call<Runtime>,
) -> bool {
	use pallet_asset_conversion::Call;
	let target = paseo_runtime_constants::ProtectedAssetLocation::get();
	match call {
		// Both sides of a liquidity operation move between the signer and the pool.
		Call::add_liquidity { asset1, asset2, .. } |
		Call::remove_liquidity { asset1, asset2, .. } => **asset1 == target || **asset2 == target,

		// A swap moves every asset along the path.
		Call::swap_exact_tokens_for_tokens { path, .. } |
		Call::swap_tokens_for_exact_tokens { path, .. } => path.iter().any(|asset| **asset == target),

		// `create_pool` charges `PoolSetupFee` in the NATIVE asset and moves neither side of the
		// pair; `touch` pays a native deposit to create the pool's accounts. Neither moves the
		// protected asset, so neither is gated.
		Call::create_pool { .. } | Call::touch { .. } => false,

		// Uninhabited placeholder variant generated by FRAME; never constructed.
		Call::__Ignore(..) => false,
	}
}

fn assets_call_targets_protected_asset(call: &pallet_assets::Call<Runtime>) -> bool {
	let target = paseo_runtime_constants::ProtectedAssetLocation::get();
	match call {
		pallet_assets::Call::transfer { id, .. } |
		pallet_assets::Call::transfer_keep_alive { id, .. } |
		pallet_assets::Call::transfer_all { id, .. } |
		pallet_assets::Call::burn { id, .. } |
		pallet_assets::Call::transfer_approved { id, .. } |
		pallet_assets::Call::approve_transfer { id, .. } => *id == target,
		_ => false,
	}
}

#[cfg(test)]
mod tests {
	use super::*;
	use crate::AccountId;
	use alloc::{boxed::Box, vec};
	use xcm::latest::Location;

	fn protected() -> Location {
		paseo_runtime_constants::ProtectedAssetLocation::get()
	}

	fn native() -> Location {
		Location::parent()
	}

	fn account() -> AccountId {
		AccountId::from([0u8; 32])
	}

	/// The AMM can move the protected asset without going through `pallet_assets`, so every call
	/// of it that does must be gated. Before this was classified, a swap naming the protected
	/// asset moved it under a plain signed origin while `Assets::transfer` of the same asset
	/// stayed filtered.
	#[test]
	fn amm_calls_moving_the_protected_asset_require_authorization() {
		let cases: vec::Vec<(&str, RuntimeCall)> = vec![
			(
				"swap with the protected asset in the path",
				RuntimeCall::AssetConversion(
					pallet_asset_conversion::Call::swap_exact_tokens_for_tokens {
						path: vec![Box::new(protected()), Box::new(native())],
						amount_in: 1,
						amount_out_min: 1,
						send_to: account(),
						keep_alive: false,
					},
				),
			),
			(
				"exact-output swap with the protected asset in the path",
				RuntimeCall::AssetConversion(
					pallet_asset_conversion::Call::swap_tokens_for_exact_tokens {
						path: vec![Box::new(native()), Box::new(protected())],
						amount_out: 1,
						amount_in_max: 1,
						send_to: account(),
						keep_alive: false,
					},
				),
			),
			(
				"add_liquidity naming the protected asset",
				RuntimeCall::AssetConversion(pallet_asset_conversion::Call::add_liquidity {
					asset1: Box::new(native()),
					asset2: Box::new(protected()),
					amount1_desired: 1,
					amount2_desired: 1,
					amount1_min: 0,
					amount2_min: 0,
					mint_to: account(),
				}),
			),
			(
				"remove_liquidity naming the protected asset",
				RuntimeCall::AssetConversion(pallet_asset_conversion::Call::remove_liquidity {
					asset1: Box::new(protected()),
					asset2: Box::new(native()),
					lp_token_burn: 1,
					amount1_min_receive: 0,
					amount2_min_receive: 0,
					withdraw_to: account(),
				}),
			),
		];
		for (what, call) in cases {
			assert!(
				PeopleValueTransferFilter::contains(&call),
				"`{what}` moves the protected asset but is not classified as a value transfer",
			);
		}
	}

	/// The gate must not be broader than the movement it exists to catch.
	#[test]
	fn amm_calls_that_move_no_protected_asset_are_not_gated() {
		let unrelated = Location::new(1, [xcm::latest::Junction::Parachain(4242)]);
		let cases: vec::Vec<(&str, RuntimeCall)> = vec![
			(
				"create_pool charges PoolSetupFee in native and moves neither side",
				RuntimeCall::AssetConversion(pallet_asset_conversion::Call::create_pool {
					asset1: Box::new(native()),
					asset2: Box::new(protected()),
				}),
			),
			(
				"a swap over a path with no protected asset",
				RuntimeCall::AssetConversion(
					pallet_asset_conversion::Call::swap_exact_tokens_for_tokens {
						path: vec![Box::new(native()), Box::new(unrelated.clone())],
						amount_in: 1,
						amount_out_min: 1,
						send_to: account(),
						keep_alive: false,
					},
				),
			),
		];
		for (what, call) in cases {
			assert!(
				!PeopleValueTransferFilter::contains(&call),
				"`{what}` was gated, but it moves no protected asset",
			);
		}
	}

	/// The control: the direct path this whole filter exists for. If this ever stopped being
	/// gated, the assertions above would still pass while the protection was gone.
	#[test]
	fn a_direct_protected_asset_transfer_is_gated() {
		let call = RuntimeCall::Assets(pallet_assets::Call::transfer {
			id: protected(),
			target: sp_runtime::MultiAddress::Id(account()),
			amount: 1,
		});
		assert!(PeopleValueTransferFilter::contains(&call));
	}
}
