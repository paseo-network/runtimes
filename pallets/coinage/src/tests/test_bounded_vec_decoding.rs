//! Tests that BoundedVec fields in Call and AsCoinageInfo fail to decode when exceeding bounds.
//!
//! The bound is `MaxConsolidation` which is set to 16 in the mock configuration.
//!
//! The approach here is:
//! 1. Create a valid structure with some elements in the BoundedVec
//! 2. Encode it to get the byte representation
//! 3. Locate where the vec is encoded (compact length prefix + elements)
//! 4. Replace that portion with an encoding at max bound - verify it decodes
//! 5. Replace that portion with an encoding beyond max bound - verify it fails to decode
//!
//! Arguably those tests can't prove that the actual Call and Transaction Extensions are bounded
//! but they can at least ensure the bounding works for aliases and alias_proofs that are tested
//! for.

use crate::{
	extension::AsCoinageInfo,
	mock::{new_test_ext, LitePeopleProof, PeopleProof, Proof, Test, MAX_CONSOLIDATION},
	Call,
};
use codec::{Decode, Encode};
use frame_support::BoundedVec;
use indiv_support::traits::Alias;
use sp_runtime::bounded_vec;

/// Size of an Alias in bytes (32 bytes).
const ALIAS_SIZE: usize = 32;

/// Helper to create a mock alias for testing.
fn mock_alias(seed: u8) -> Alias {
	Alias::from([seed; 32])
}

/// Helper to create a mock proof for testing.
///
/// The bytes are arbitrary — these tests exercise decoding bounds, not signature validity —
/// but we size the buffer to match a real single-context proof.
fn mock_proof(seed: u8) -> Proof {
	vec![
		seed;
		verifiable::ring::ring_signature_size::<
			verifiable::ring::bandersnatch::BandersnatchSha512Ell2,
		>(1)
	]
	.try_into()
	.expect("proof fits within max bound")
}

/// SCALE-encoded length of a single mock proof. Used to compute offsets and element sizes
/// when manipulating encoded test fixtures.
fn mock_proof_encoded_len() -> usize {
	mock_proof(0).encode().len()
}

/// Helper to encode a compact length prefix for SCALE encoding.
fn compact_encode_len(len: u32) -> Vec<u8> {
	codec::Compact(len).encode()
}

/// Replace the vec at `vec_start_offset` in `encoded` with a new vec containing `new_count`
/// elements. Each element has size `element_size` and is generated by `element_gen`.
fn replace_vec_with_longer<F>(
	encoded: &[u8],
	vec_start_offset: usize,
	original_count: u32,
	new_count: u32,
	element_size: usize,
	element_gen: F,
) -> Vec<u8>
where
	F: Fn(u32) -> Vec<u8>,
{
	let original_compact_len = compact_encode_len(original_count).len();
	let original_vec_size = original_compact_len + (original_count as usize * element_size);

	// Build the new vec encoding
	let mut new_vec_encoded = compact_encode_len(new_count);
	for i in 0..new_count {
		new_vec_encoded.extend(element_gen(i));
	}

	// Construct the modified encoding:
	// [prefix before vec] + [new vec encoding] + [suffix after original vec]
	let mut result = Vec::new();
	result.extend(&encoded[..vec_start_offset]);
	result.extend(&new_vec_encoded);
	result.extend(&encoded[vec_start_offset + original_vec_size..]);

	result
}

// ============================================================================
// Tests for Call decoding bounds
// ============================================================================

#[test]
fn unload_recycler_into_coin_bounded_vec_decoding() {
	new_test_ext().execute_with(|| {
		// Create a valid call with 2 aliases
		let aliases: BoundedVec<Alias, _> = bounded_vec![mock_alias(0), mock_alias(1)];
		let call = Call::<Test>::unload_recycler_into_coin {
			aliases,
			value: 0i8,
			index: 0u32,
			revision: 0u32,
			to: 1u64,
		};

		let encoded = call.encode();
		let vec_start_offset = 1; // After call index

		// Test at max bound - should decode
		let at_max = replace_vec_with_longer(
			&encoded,
			vec_start_offset,
			2,
			MAX_CONSOLIDATION,
			ALIAS_SIZE,
			|i| mock_alias(i as u8).encode(),
		);
		let result = Call::<Test>::decode(&mut &at_max[..]);
		assert!(result.is_ok(), "Should decode at max bound ({MAX_CONSOLIDATION})");
		if let Ok(Call::unload_recycler_into_coin { aliases, .. }) = result {
			assert_eq!(aliases.len() as u32, MAX_CONSOLIDATION);
		}

		// Test beyond max bound - should fail
		let beyond_max = replace_vec_with_longer(
			&encoded,
			vec_start_offset,
			2,
			MAX_CONSOLIDATION + 1,
			ALIAS_SIZE,
			|i| mock_alias(i as u8).encode(),
		);
		let result = Call::<Test>::decode(&mut &beyond_max[..]);
		let over = MAX_CONSOLIDATION + 1;
		assert!(
			result.is_err(),
			"Should fail to decode with {over} aliases (max is {MAX_CONSOLIDATION})"
		);
	});
}

